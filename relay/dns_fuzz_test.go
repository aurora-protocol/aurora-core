package relay

import "testing"

func FuzzSocketDNSQuestionResponseRoundTrip(f *testing.F) {
	f.Add([]byte{
		0x12, 0x34, 0x01, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
		0x07, 'e', 'x', 'a', 'm', 'p', 'l', 'e', 0x03, 'c', 'o', 'm', 0x00,
		0x00, socketDNSTypeA, 0x00, socketDNSClassIN,
	})
	f.Add([]byte{
		0x12, 0x34, 0x01, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x01,
		0x07, 'e', 'x', 'a', 'm', 'p', 'l', 'e', 0x03, 'c', 'o', 'm', 0x00,
		0x00, socketDNSTypeAAAA, 0x00, socketDNSClassIN,
		0x00, 0x00, 0x29, 0x10, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
	})
	f.Add([]byte{
		0x12, 0x34, 0x01, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
		0x07, 'e', 'x', 'a', 'm', 'p', 'l', 'e', 0x03, 'c', 'o', 'm', 0x00,
		0x00, socketDNSTypeSVCB, 0x00, socketDNSClassIN,
	})

	f.Fuzz(func(t *testing.T, message []byte) {
		question, err := parseSocketDNSQuestion(message)
		if err != nil {
			return
		}
		response := buildSocketDNSResponse(question, socketDNSRCodeOK, nil, 1)
		if err := validateSocketDNSResponse(question, response, ExitPolicy{}); err != nil {
			t.Fatalf("round-trip validation failed: %v", err)
		}
	})
}
